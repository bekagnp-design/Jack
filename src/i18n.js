const STORAGE_KEY = 'eleven.lang';
let current = 'en';
try { current = localStorage.getItem(STORAGE_KEY) === 'ka' ? 'ka' : 'en'; } catch { /* storage blocked */ }
const listeners = new Set();

export function getLang() { return current; }

export function setLang(lang) {
  current = lang === 'ka' ? 'ka' : 'en';
  try { localStorage.setItem(STORAGE_KEY, current); } catch { /* ignore */ }
  document.documentElement.lang = current;
  for (const fn of listeners) fn(current);
}

export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function countryName(code) {
  const row = COUNTRIES.find((c) => c[0] === code);
  return row ? (current === 'ka' ? row[2] : row[1]) : code;
}
